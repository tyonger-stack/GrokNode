import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { openUpstream0721 } from "./upstream-0721.mjs";
import { extractUpstreamDeclarations } from "./upstream-declarations.mjs";

const repoRoot = fileURLToPath(new URL("../../", import.meta.url));
const defaultOutput = path.join(repoRoot, "source/electron-main/vault/upstream-vault-parsers.generated.mjs");

export const UPSTREAM_VAULT_SOURCES = Object.freeze({
  view: "dist/renderer/assets/chunk-view-Cwu5IFAB.js",
  cardFields: "dist/renderer/assets/chunk-vault-card-fields-BBZgWwVF.js",
  csvParse: "dist/renderer/assets/chunk-csv-parse-C5LpQq5n.js",
  mainApp: "dist/electron-main/main-app.cjs",
});

export async function buildUpstreamVaultParsers({
  archive: archiveInput,
  output = defaultOutput,
} = {}) {
  const archive = archiveInput ?? await openUpstream0721();
  const view = archive.read(UPSTREAM_VAULT_SOURCES.view).toString("utf8");
  const cardFields = archive.read(UPSTREAM_VAULT_SOURCES.cardFields).toString("utf8");
  const csvParse = archive.read(UPSTREAM_VAULT_SOURCES.csvParse).toString("utf8");
  const mainApp = archive.read(UPSTREAM_VAULT_SOURCES.mainApp).toString("utf8");

  const viewExtraction = extractUpstreamDeclarations({
    code: view,
    exports: {
      parseCsv: "Me",
      planLogin: "ke",
      planCard: "Ae",
      duplicateKeys: "je",
      parseExpiry: "Ee",
      formatExpiry: "De",
    },
    strict: true,
  });
  const cardExtraction = extractUpstreamDeclarations({
    code: cardFields,
    exports: { validateCardNumber: "re", cardPhotoValues: "ce", m: "re" },
    strict: true,
  });
  const mainExtraction = extractUpstreamDeclarations({
    code: mainApp,
    exports: {
      parseRecognizedCard: "mat",
      detectCardNumber: "gat",
      detectCardBrand: "HMn",
      validateSecurityCode: "cMn",
    },
    strict: true,
  });

  const root = await mkdtemp(path.join(os.tmpdir(), "grok-vault-upstream-"));
  try {
    await writeFile(path.join(root, "view.mjs"), viewExtraction.code);
    await writeFile(path.join(root, "chunk-vault-card-fields-BBZgWwVF.js"), cardExtraction.code);
    await writeFile(path.join(root, "main.mjs"), mainExtraction.code);
    await writeFile(path.join(root, "chunk-csv-parse-C5LpQq5n.js"), csvParse);
    await writeFile(path.join(root, "entry.mjs"), [
      'export { parseCsv, planLogin, planCard, duplicateKeys, parseExpiry, formatExpiry } from "./view.mjs";',
      'export { validateCardNumber, cardPhotoValues } from "./chunk-vault-card-fields-BBZgWwVF.js";',
      'export { parseRecognizedCard, detectCardNumber, detectCardBrand, validateSecurityCode } from "./main.mjs";',
      "",
    ].join("\n"));
    const bundled = await build({
      entryPoints: [path.join(root, "entry.mjs")],
      bundle: true,
      write: false,
      format: "esm",
      platform: "neutral",
      target: "es2022",
      legalComments: "none",
      logLevel: "silent",
    });
    const provenance = {
      upstreamIdentity: archive.identity,
      sources: {
        [UPSTREAM_VAULT_SOURCES.view]: viewExtraction.provenance,
        [UPSTREAM_VAULT_SOURCES.cardFields]: cardExtraction.provenance,
        [UPSTREAM_VAULT_SOURCES.mainApp]: mainExtraction.provenance,
      },
      inputSha256: {
        [UPSTREAM_VAULT_SOURCES.view]: viewExtraction.inputSha256,
        [UPSTREAM_VAULT_SOURCES.cardFields]: cardExtraction.inputSha256,
        [UPSTREAM_VAULT_SOURCES.mainApp]: mainExtraction.inputSha256,
      },
    };
    const bundledCode = bundled.outputFiles[0].text.replaceAll(root, "<upstream>");
    const contents = [
      "// Generated by scripts/lib/vault-0721.mjs from the pinned Grok Bot 0.72.1 ASAR. Do not edit.",
      "// provenance=" + JSON.stringify(provenance),
      bundledCode,
      "",
    ].join("");
    await mkdir(path.dirname(output), { recursive: true });
    await writeFile(output, contents, "utf8");
    return { output, provenance, bytes: contents.length };
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

export async function loadUpstreamVaultParsers(options = {}) {
  const built = await buildUpstreamVaultParsers(options);
  return import(built.output);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await buildUpstreamVaultParsers();
  console.log(JSON.stringify({ output: result.output, bytes: result.bytes, upstream: result.provenance.upstreamIdentity }));
}
