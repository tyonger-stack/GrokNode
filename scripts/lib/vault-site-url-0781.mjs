import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { openUpstream0781 } from "./upstream-0781.mjs";
import { extractUpstreamDeclarations } from "./upstream-declarations.mjs";

const repoRoot = fileURLToPath(new URL("../../", import.meta.url));
const defaultOutput = path.join(repoRoot, "source/electron-main/vault/upstream-vault-site-url.generated.mjs");

// Official Grok Bot 0.78.1 login-dialog chunk (Team Bot vault family). Byte offsets
// recorded 2026-10-28 from `rea-grokbot-0781/app/dist/renderer/assets/`:
//   U  @5304  (99,133 B packed public-suffix tries), H @5152 (exception tries),
//   K  @105091 (getDomain), G @104653 (suffixLookup), Q @109801 (siteHostname),
//   we @119515 (officialLoginDisplayDomain: K(Q(e),{allowPrivateDomains:!0}) ?? hostname).
export const UPSTREAM_SITE_URL_SOURCES = Object.freeze({
  loginDialogs: "dist/renderer/assets/chunk-grok-bot-vault-login-dialogs-Bhx1bdrA.js",
});

export async function buildUpstreamSiteUrl0781({
  archive: archiveInput,
  output = defaultOutput,
} = {}) {
  const archive = archiveInput ?? await openUpstream0781();
  const code = archive.read(UPSTREAM_SITE_URL_SOURCES.loginDialogs).toString("utf8");

  const extraction = extractUpstreamDeclarations({
    code,
    exports: {
      siteHostname: "Q",
      emptyParseResult: "ne",
      suffixLookup: "G",
      getDomain: "K",
      officialLoginDisplayDomain: "we",
    },
    strict: true,
  });

  const root = await mkdtemp(path.join(os.tmpdir(), "grok-vault-site-url-"));
  try {
    const sourceModule = path.join(root, UPSTREAM_SITE_URL_SOURCES.loginDialogs);
    await mkdir(path.dirname(sourceModule), { recursive: true });
    await writeFile(sourceModule, extraction.code);
    await writeFile(path.join(root, "entry.mjs"), [
      'export { siteHostname, emptyParseResult, suffixLookup, getDomain, officialLoginDisplayDomain } from "./' +
        UPSTREAM_SITE_URL_SOURCES.loginDialogs + '";',
      "",
    ].join("\n"));
    const bundled = await build({
      entryPoints: [path.join(root, "entry.mjs")],
      bundle: true,
      write: false,
      format: "esm",
      platform: "neutral",
      target: "es2022",
      legalComments: "none",
      logLevel: "silent",
    });
    const provenance = {
      upstreamIdentity: archive.identity,
      sources: { [UPSTREAM_SITE_URL_SOURCES.loginDialogs]: extraction.provenance },
      inputSha256: { [UPSTREAM_SITE_URL_SOURCES.loginDialogs]: extraction.inputSha256 },
      behaviourChange:
        "Official 0.78.1 uses the PSL parser for login-row display domain only " +
        "(we: K(Q(e),{allowPrivateDomains:!0}) ?? hostname) and never rejects at save time. " +
        "Local hardening (documented delta, not official parity): local-vault-backend refuses " +
        "sites whose hostname is a KNOWN public suffix with an empty registrable domain " +
        "(e.g. https://com, https://co.uk) with the existing 'invalid-website' problem; " +
        "unknown-TLD/internal hostnames (e.g. localhost) stay accepted, mirroring the official fallback.",
    };
    const bundledCode = bundled.outputFiles[0].text.replaceAll(root, "<upstream>");
    const contents = [
      "// Generated by scripts/lib/vault-site-url-0781.mjs from the pinned Grok Bot 0.78.1 ASAR. Do not edit.",
      "// provenance=" + JSON.stringify(provenance),
      bundledCode,
      "",
    ].join("");
    await mkdir(path.dirname(output), { recursive: true });
    await writeFile(output, contents, "utf8");
    return { output, provenance, bytes: contents.length };
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

export async function loadUpstreamSiteUrl0781(options = {}) {
  const built = await buildUpstreamSiteUrl0781(options);
  return import(built.output);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await buildUpstreamSiteUrl0781();
  console.log(JSON.stringify({ output: result.output, bytes: result.bytes, upstream: result.provenance.upstreamIdentity }));
}
