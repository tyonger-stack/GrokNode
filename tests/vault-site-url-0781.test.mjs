const root = fileURLToPath(new URL("../", import.meta.url));
const generatedPath = path.join(root, "source/electron-main/vault/upstream-vault-site-url.generated.mjs");
const officialChunkPath = path.resolve(root, "..", "rea-grokbot-0781/app/dist/renderer/assets/chunk-grok-bot-vault-login-dialogs-Bhx1bdrA.js");
const snapshotSkip = existsSync(officialChunkPath) ? false : "rea-grokbot-0781 snapshot is not present on this machine";

const GENERATED_HEADER = "// Generated by scripts/lib/vault-site-url-0781.mjs from the pinned Grok Bot 0.78.1 ASAR. Do not edit.";
const UPSTREAM_ASAR_SHA = "e8d5e10f94f8b52cd02f696599c8e6503420ad85ceed7b41a27bbff7bff22f4d";
// Exact official snippets this module is extracted from (chunk-grok-bot-vault-login-dialogs-Bhx1bdrA.js):
// K @105091 (getDomain) and we @119515 (row display domain with full-hostname fallback).
// esbuild pretty-prints the emitted module, so emitted-body comparisons normalize whitespace;
// the official chunk itself is asserted verbatim in the snapshot tests below.
const OFFICIAL_GET_DOMAIN_SNIPPET = "function K(e,t={}){return z(re),B(e,3,G,t,re).domain}";
const OFFICIAL_DISPLAY_DOMAIN_SNIPPET =
  "function we(e){let t=Q(e);return t===null?null:K(t,{allowPrivateDomains:!0})??t}";
const squash = (text) =>
  text.replace(/!0/g, "true").replace(/!1/g, "false").replace(/\s+/g, "").replace(/;\}/g, "}");

class AesGcmSecureStorageCodec {
  #key = createHash("sha256").update("synthetic-vault-site-url-test-key").digest();

  isEncryptionAvailable() {
    return true;
  }

  encryptString(value) {
    const iv = randomBytes(12);
    const cipher = createCipheriv("aes-256-gcm", this.#key, iv);
    return Buffer.concat([iv, cipher.update(value, "utf8"), cipher.final(), cipher.getAuthTag()]);
  }

  decryptString(value) {
    const iv = value.subarray(0, 12);
    const tag = value.subarray(value.length - 16);
    const decipher = createDecipheriv("aes-256-gcm", this.#key, iv);
    decipher.setAuthTag(tag);
    return Buffer.concat([decipher.update(value.subarray(12, value.length - 16)), decipher.final()]).toString("utf8");
  }
}

async function loadVaultModule() {
  const output = path.join(root, "node_modules/.cache/vault-site-url-0781.cjs");
  await build({
    stdin: {
      contents: 'export {createLocalVaultBackend, VaultInvalidArgumentError} from "./source/electron-main/vault/local-vault-backend.ts";',
      resolveDir: root,
      loader: "ts",
    },
    outfile: output,
    bundle: true,
    platform: "node",
    format: "cjs",
    packages: "external",
    logLevel: "error",
  });
  return createRequire(import.meta.url)(output);
}

test("0.78.1 site-url module carries provenance from the pinned 0.78.1 extraction", async () => {
  const source = await readFile(generatedPath, "utf8");
  assert.ok(source.startsWith(GENERATED_HEADER), "generated header must pin the 0.78.1 generator");
  assert.ok(source.includes(UPSTREAM_ASAR_SHA), "provenance must record the 0.78.1 asar digest");
  assert.ok(source.includes("chunk-grok-bot-vault-login-dialogs-Bhx1bdrA.js"), "provenance must name the source chunk");
  assert.ok(source.includes("behaviourChange"), "provenance must record the local-hardening delta");
  // Byte-consistency: the emitted module embeds the official function bodies (esbuild-normalized).
  assert.ok(squash(source).includes(squash(OFFICIAL_GET_DOMAIN_SNIPPET)), "emitted getDomain body matches the official chunk");
  assert.ok(squash(source).includes(squash(OFFICIAL_DISPLAY_DOMAIN_SNIPPET)), "emitted display-domain body matches the official chunk");
});

test("extracted PSL parser reproduces the official hostname semantics", async () => {
  const siteUrl = await import("../source/electron-main/vault/upstream-vault-site-url.generated.mjs");
  // siteHostname (official Q): URL-aware, protocol-completing, lowercase, www-stripped.
  assert.equal(siteUrl.siteHostname("example.com"), "example.com");
  assert.equal(siteUrl.siteHostname("https://accounts.google.com/signin"), "accounts.google.com");
  assert.equal(siteUrl.siteHostname("https://WWW.Example.COM"), "example.com");
  assert.equal(siteUrl.siteHostname("not a site"), null);
  // getDomain (official K): registrable domain, private suffixes honoured with allowPrivateDomains.
  assert.equal(siteUrl.getDomain("a.example.co.uk", { allowPrivateDomains: true }), "example.co.uk");
  assert.equal(siteUrl.getDomain("accounts.google.com", { allowPrivateDomains: true }), "google.com");
  assert.equal(siteUrl.getDomain("test.blogspot.com", { allowPrivateDomains: true }), "test.blogspot.com");
  // Bare known public suffixes have an empty registrable domain…
  assert.equal(siteUrl.getDomain("com", { allowPrivateDomains: true }), null);
  assert.equal(siteUrl.getDomain("blogspot.com", { allowPrivateDomains: true }), null);
  // …while unknown TLDs and internal hosts fall out the same way (official fallback territory).
  assert.equal(siteUrl.getDomain("localhost", { allowPrivateDomains: true }), null);
  // suffixLookup (official G): distinguishes known suffixes from unknown TLDs.
  const known = siteUrl.emptyParseResult();
  siteUrl.suffixLookup("com", { allowIcannDomains: true, allowPrivateDomains: true }, known);
  assert.equal(known.isIcann, true);
  const internal = siteUrl.emptyParseResult();
  siteUrl.suffixLookup("localhost", { allowIcannDomains: true, allowPrivateDomains: true }, internal);
  assert.equal(internal.isIcann, false);
  assert.equal(internal.isPrivate, false);
  // officialLoginDisplayDomain (official we): the anchored display semantics.
  assert.equal(siteUrl.officialLoginDisplayDomain("accounts.google.com"), "google.com");
  assert.equal(siteUrl.officialLoginDisplayDomain("com"), "com");
  assert.equal(siteUrl.officialLoginDisplayDomain("localhost"), "localhost");
  assert.equal(siteUrl.officialLoginDisplayDomain("not a site"), null);
});

test("local Vault refuses known public-suffix sites and keeps normal or internal hosts", async (t) => {
  const modules = await loadVaultModule();
  const temporary = await mkdtemp(path.join(os.tmpdir(), "vault-site-url-"));
  t.after(async () => rm(temporary, { recursive: true, force: true }));
  const vault = modules.createLocalVaultBackend({
    accountScope: "a".repeat(64),
    storePath: path.join(temporary, "grok-bot-vault.json"),
    codec: new AesGcmSecureStorageCodec(),
    cardsEnabled: true,
    now: () => Date.parse("2026-10-01T12:00:00Z"),
  });
  const login = (sites) => ({ title: "Synthetic", username: "user@example.test", notes: "", sites, password: "synthetic-password" });
  await assert.rejects(
    () => vault.putGrokBotVaultCredential({ id: "", ...login(["https://com"]) }),
    (error) => error instanceof modules.VaultInvalidArgumentError && error.message === "invalid-website",
  );
  await assert.rejects(
    () => vault.putGrokBotVaultCredential({ id: "", ...login(["https://co.uk"]) }),
    (error) => error instanceof modules.VaultInvalidArgumentError && error.message === "invalid-website",
  );
  const created = await vault.putGrokBotVaultCredential({ id: "", ...login(["example.com"]) });
  assert.deepEqual(created.sites, ["https://example.com"]);
  const internal = await vault.putGrokBotVaultCredential({ id: "", ...login(["localhost:8080"]) });
  assert.deepEqual(internal.sites, ["https://localhost:8080"]);
});

test(`regeneration from the ${"0.78.1"} snapshot is byte-identical to the committed module`, { skip: snapshotSkip }, async () => {
  const { openUpstream0781 } = await import("../scripts/lib/upstream-0781.mjs");
  const { buildUpstreamSiteUrl0781 } = await import("../scripts/lib/vault-site-url-0781.mjs");
  const temporary = await mkdtemp(path.join(os.tmpdir(), "vault-site-url-regen-"));
  try {
    const archive = await openUpstream0781();
    const output = path.join(temporary, "vault-site-url.mjs");
    await buildUpstreamSiteUrl0781({ archive, output });
    const [expected, actual] = await Promise.all([readFile(generatedPath), readFile(output)]);
    assert.ok(expected.equals(actual), "regenerated module must be byte-identical to the committed extraction");
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
});

