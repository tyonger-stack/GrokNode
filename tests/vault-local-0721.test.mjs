const root = fileURLToPath(new URL("../", import.meta.url));
const output = path.join(root, "node_modules/.cache/vault-local-0721.cjs");
const evidenceDir = process.env.R1_EVIDENCE_DIR;

function record(name, value) {
  if (evidenceDir === undefined) return;
  mkdirSync(evidenceDir, { recursive: true });
  writeFileSync(path.join(evidenceDir, name + ".json"), JSON.stringify(value, null, 2));
}

class AesGcmSecureStorageCodec {
  #key = createHash("sha256").update("synthetic-vault-test-key").digest();

  isEncryptionAvailable() {
    return true;
  }

  encryptString(value) {
    const iv = randomBytes(12);
    const cipher = createCipheriv("aes-256-gcm", this.#key, iv);
    return Buffer.concat([iv, cipher.update(value, "utf8"), cipher.final(), cipher.getAuthTag()]);
  }

  decryptString(value) {
    const iv = value.subarray(0, 12);
    const tag = value.subarray(value.length - 16);
    const ciphertext = value.subarray(12, value.length - 16);
    const decipher = createDecipheriv("aes-256-gcm", this.#key, iv);
    decipher.setAuthTag(tag);
    return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString("utf8");
  }
}

class UnavailableCodec extends AesGcmSecureStorageCodec {
  isEncryptionAvailable() {
    return false;
  }
}

async function loadModules() {
  await mkdir(path.dirname(output), { recursive: true });
  await build({
    stdin: {
      contents: [
        'export {createLocalVaultBackend, VaultEncryptionUnavailableError, VaultInvalidArgumentError, VaultNotFoundError} from "./source/electron-main/vault/local-vault-backend.ts";',
        'export {createLocalBackendHandlers0721} from "./source/electron-main/local-backend-handlers-0721.ts";',
      ].join("\n"),
      resolveDir: root,
      loader: "ts",
    },
    outfile: output,
    bundle: true,
    platform: "node",
    format: "cjs",
    packages: "external",
    logLevel: "error",
  });
  return createRequire(import.meta.url)(output);
}

function backendFor(modules, storePath, accountScope = "a".repeat(64), overrides = {}) {
  return modules.createLocalVaultBackend({
    accountScope,
    storePath,
    codec: new AesGcmSecureStorageCodec(),
    cardsEnabled: true,
    now: () => Date.parse("2026-10-01T12:00:00Z"),
    ...overrides,
  });
}

